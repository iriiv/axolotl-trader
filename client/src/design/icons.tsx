export interface PixelIconProps {
  /** сторона в px */
  size?: number
  className?: string
  style?: CSSProperties
  title?: string
}

function makeIcon(name: IconName) {
  return function PixelIcon({ size = 16, className, style, title }: PixelIconProps) {
    const { grid, rows } = GLYPHS[name]
    return (
      <svg
        className={className}
        style={style}
        width={size}
        height={size}
        viewBox={`0 0 ${grid} ${grid}`}
        shapeRendering="crispEdges"
        role={title ? 'img' : undefined}
        aria-label={title}
        focusable="false"
      >
        {title ? <title>{title}</title> : null}
        {rows.map((row, y) =>
          row.split('').map((ch, x) =>
            ch === '#' ? (
              <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="currentColor" />
            ) : null,
          ),
        )}
      </svg>
    )
  }
}

